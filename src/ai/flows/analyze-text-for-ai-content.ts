'use server';
/**
 * @fileOverview Analyzes text to determine the likelihood of it being AI-generated.
 *
 * - analyzeTextForAIContent - A function that analyzes the text.
 * - AnalyzeTextForAIContentInput - The input type for the analyzeTextForAIContent function.
 * - AnalyzeTextForAIContentOutput - The return type for the analyzeTextForAIContent function.
 */

import {ai} from '@/ai/genkit';
import {z} from 'genkit';

const AnalyzeTextForAIContentInputSchema = z.object({
  text: z.string().describe('The text to analyze for AI content.'),
});
export type AnalyzeTextForAIContentInput = z.infer<typeof AnalyzeTextForAIContentInputSchema>;

const AnalyzeTextForAIContentOutputSchema = z.object({
  score: z.number().describe('The likelihood score that the text was generated by AI (0-1).'),
});
export type AnalyzeTextForAIContentOutput = z.infer<typeof AnalyzeTextForAIContentOutputSchema>;

export async function analyzeTextForAIContent(input: AnalyzeTextForAIContentInput): Promise<AnalyzeTextForAIContentOutput> {
  return analyzeTextForAIContentFlow(input);
}

const prompt = ai.definePrompt({
  name: 'analyzeTextForAIContentPrompt',
  input: {schema: AnalyzeTextForAIContentInputSchema},
  output: {schema: AnalyzeTextForAIContentOutputSchema},
  prompt: `Analyze the following text and determine the likelihood that it was generated by AI. Provide a score between 0 and 1, where 0 means definitely human-written and 1 means definitely AI-generated.\n\nText: {{text}}`,
});

const analyzeTextForAIContentFlow = ai.defineFlow(
  {
    name: 'analyzeTextForAIContentFlow',
    inputSchema: AnalyzeTextForAIContentInputSchema,
    outputSchema: AnalyzeTextForAIContentOutputSchema,
  },
  async input => {
    const {output} = await prompt(input);
    return output!;
  }
);
